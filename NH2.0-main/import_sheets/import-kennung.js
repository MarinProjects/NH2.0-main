const kennungen = rawData
  .trim()
  .split(/[\s,]+/)
  .filter(Boolean)
  .map((entry) => {
    const [personalnummer, kennung] = entry.split(':');

    return {
      personalnummer: Number(personalnummer),
      kennung
    };
  });

async function importKennungen() {
  

  try {
    await mongoose.connect(
  'mongodb://127.0.0.1:27017/neue_heimat_xx'
);

    console.log('MongoDB verbunden.');

    const personalnummern =
      kennungen.map((x) => x.personalnummer);

    const existingPersons =
      await Person.find(
        {
          personalnummer: {
            $in: personalnummern
          }
        },
        {
          personalnummer: 1
        }
      ).lean();

    const existingSet =
      new Set(
        existingPersons.map(
          (p) => Number(p.personalnummer)
        )
      );

    const operations =
      kennungen
        .filter(
          (x) =>
            existingSet.has(
              x.personalnummer
            )
        )
        .map((x) => ({
          updateOne: {
            filter: {
              personalnummer:
                x.personalnummer
            },
            update: {
              $set: {
                kennung: x.kennung
              }
            }
          }
        }));

    if (operations.length > 0) {
      const result =
        await Person.bulkWrite(
          operations,
          {
            ordered: false
          }
        );

      console.log(
        `Gefunden/aktualisiert: ${
          result.matchedCount ??
          operations.length
        }`
      );
    } else {
      console.log(
        'Keine passenden Personalnummern in der Datenbank gefunden.'
      );
    }

    const notFound =
      kennungen.filter(
        (x) =>
          !existingSet.has(
            x.personalnummer
          )
      );

    if (notFound.length > 0) {
      console.log(
        '\nNicht gefundene Personalnummern:'
      );

      notFound.forEach(
        (x) =>
          console.log(
            `- ${x.personalnummer} (${x.kennung})`
          )
      );
    }

    console.log(
      '\n----------------------------------------'
    );

    console.log(
      `Zuordnungen in Importliste: ${kennungen.length}`
    );

    console.log(
      `In Datenbank gefunden: ${operations.length}`
    );

    console.log(
      `Nicht gefunden: ${notFound.length}`
    );

  } catch (error) {

    console.error(
      'Fehler beim Kennungs-Import:',
      error
    );

    process.exitCode = 1;

  } finally {

    await mongoose.disconnect();

  }
}

importKennungen();